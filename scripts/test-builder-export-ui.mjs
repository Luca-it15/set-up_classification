import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { createServer } from 'vite';
import { DEFAULT_SETTINGS } from '../src/defaultSettings.js';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.AWDF_NODE_MODULES ? path.join(process.env.AWDF_NODE_MODULES, 'playwright') : 'playwright');
const out = path.resolve('.tmp-evidence-checks/builder-export'); fs.mkdirSync(out, { recursive: true });
const report = JSON.parse(fs.readFileSync('.tmp-evidence-checks/description/report.json'));
const settings = structuredClone(DEFAULT_SETTINGS); settings.initialized = true; settings.workspace.folders = ['C:/fixture'];
const server = await createServer({ server: { host: '127.0.0.1', port: 4321, strictPort: true, watch: { ignored: ['**/.tmp-evidence-checks/**'] } } }); await server.listen();
let browser;
try {
  try { browser = await chromium.launch({ headless: true }); } catch { browser = await chromium.launch({ headless: true, channel: 'msedge' }); }
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/report', route => route.fulfill({ json: report }));
  await page.route('**/api/settings', route => route.fulfill({ json: settings }));
  await page.goto('http://127.0.0.1:4321');
  await page.getByText(report.workspace.name, { exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'Condividi setup', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  const [htmlDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Esporta HTML', exact: true }).click()]);
  const htmlPath = path.join(out, 'ai-setup.html'); await htmlDownload.saveAs(htmlPath);
  const [pngDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Esporta PNG', exact: true }).click()]);
  const pngPath = path.join(out, 'ai-setup.png'); await pngDownload.saveAs(pngPath);
  const png = fs.readFileSync(pngPath); assert.equal(png.subarray(1, 4).toString(), 'PNG'); assert.ok(png.readUInt32BE(16) >= 1400); assert.ok(png.readUInt32BE(20) > 1000);
  // Failed PNG encoding stays recoverable, without dismissing the dialog.
  await page.evaluate(() => { window.originalToBlob = HTMLCanvasElement.prototype.toBlob; HTMLCanvasElement.prototype.toBlob = function(callback) { callback(null); }; });
  await page.getByRole('button', { name: 'Esporta PNG', exact: true }).click();
  await page.getByText('Impossibile creare il PNG. Riprova oppure esporta HTML.', { exact: true }).waitFor();
  await page.evaluate(() => { HTMLCanvasElement.prototype.toBlob = window.originalToBlob; });
  assert.equal(await page.getByRole('button', { name: 'Esporta PNG', exact: true }).isEnabled(), true);
  await page.screenshot({ path: path.join(out, 'export-dialog.png') });
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button', { name: 'Condividi setup', exact: true }).evaluate(el => el === document.activeElement), true);
  const offline = await browser.newPage(); const requests = [];
  offline.on('request', request => requests.push(request.url()));
  await offline.context().setOffline(true);
  await offline.goto(pathToFileURL(htmlPath).href);
  assert.equal(await offline.locator('#inventory .record').count(), report.components.length);
  assert.equal(await offline.locator('#links li').count(), report.relationships.length);
  assert.ok(await offline.locator('.map-frame a.hotspot').count() > 0);
  const hotspot = offline.locator('.map-frame a.hotspot').first();
  const plate = hotspot.locator('.node-plate');
  const restingStroke = await plate.evaluate(element => getComputedStyle(element).stroke);
  await hotspot.hover();
  assert.notEqual(await plate.evaluate(element => getComputedStyle(element).stroke), restingStroke);
  await offline.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await plate.evaluate(element => getComputedStyle(element).transitionDuration), '0s');
  await hotspot.click();
  assert.match(new URL(offline.url()).hash, /^#(?:tool|component|group)-/);
  assert.equal(requests.some(url => /^https?:/.test(url)), false);
  await offline.screenshot({ path: path.join(out, 'offline-html.png'), fullPage: true }); await offline.close();
  await page.getByRole('button', { name: 'Setup builder', exact: true }).click();
  await page.getByRole('button', { name: 'Scarica AGENTS.md', exact: true }).click();
  await page.getByText('Assegna un nome al setup.', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Nome del setup', { exact: true }).evaluate(el => el === document.activeElement), true);
  await page.getByLabel('Nome del setup', { exact: true }).fill('Team Aurora');
  await page.getByRole('button', { name: 'Aggiungi componente', exact: true }).click();
  await page.getByLabel('Nome componente 1', { exact: true }).fill('Manuale del progetto');
  await page.getByLabel('Tipo', { exact: true }).selectOption('knowledge_base');
  await page.getByLabel('Percorso o identificatore 1', { exact: true }).fill('handbook/');
  const [agentsDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Scarica AGENTS.md', exact: true }).click()]);
  assert.equal(agentsDownload.suggestedFilename(), 'AGENTS.md'); await agentsDownload.saveAs(path.join(out, 'AGENTS.md'));
  assert.match(fs.readFileSync(path.join(out, 'AGENTS.md'), 'utf8'), /Leggi `handbook\/`/);
  await page.getByLabel('Quando usarla (opzionale)', { exact: true }).fill('modifichi il codice');
  await page.getByLabel('Tool AI', { exact: true }).focus(); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter');
  await page.getByRole('button', { name: 'Scarica CLAUDE.md', exact: true }).waitFor();
  const [claudeDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Scarica CLAUDE.md', exact: true }).click()]);
  await claudeDownload.saveAs(path.join(out, 'CLAUDE.md'));
  assert.match(fs.readFileSync(path.join(out, 'CLAUDE.md'), 'utf8'), /Quando modifichi il codice: Leggi/);
  await page.getByRole('button', { name: 'Rimuovi componente 1', exact: true }).click();
  await page.getByRole('button', { name: 'Annulla rimozione', exact: true }).click();
  assert.equal(await page.getByLabel('Nome componente 1', { exact: true }).inputValue(), 'Manuale del progetto');
  await page.getByLabel('Dal report corrente', { exact: true }).selectOption({ index: 1 });
  await page.getByRole('button', { name: 'Aggiungi dal report', exact: true }).click();
  assert.equal(await page.locator('.builder-component').count(), 2);
  await page.screenshot({ path: path.join(out, 'builder-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Mappa setup', exact: true }).click();
  await page.getByRole('button', { name: 'Setup builder', exact: true }).click();
  assert.equal(await page.locator('.builder-component').count(), 2);
  await page.reload(); await page.getByRole('button', { name: 'Setup builder', exact: true }).click();
  assert.equal(await page.getByLabel('Nome del setup', { exact: true }).inputValue(), 'Team Aurora');
  assert.equal(await page.getByLabel('Tool AI', { exact: true }).inputValue(), 'claude_code');
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.screenshot({ path: path.join(out, 'builder-mobile.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  // Locale/theme are provided by the same settings path as the rest of the app.
  settings.viewer.language = 'de'; settings.viewer.palette = 'light';
  await page.reload(); await page.getByRole('button', { name: 'Setup-Builder', exact: true }).click();
  await page.getByRole('heading', { name: 'Setup zusammenstellen', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.lang), 'de');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  await page.screenshot({ path: path.join(out, 'builder-mobile-light-de.png'), fullPage: true });
  // Brand-new installs can enter the builder without authorizing scan folders.
  settings.initialized = false; settings.workspace.folders = []; settings.viewer.language = 'it';
  await page.reload(); await page.getByRole('button', { name: 'Costruisci senza scansione', exact: true }).click();
  await page.getByRole('heading', { name: 'Costruisci il tuo setup', exact: true }).waitFor();
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.deepEqual(errors, []);
  console.log('Builder/export UI PASS: real downloads, offline HTML, PNG failure/retry, builder validation/edit/remove/undo/import, persistence, host filenames, keyboard, mobile, German/light theme, fresh install and no browser errors.');
} finally { await browser?.close(); await server.close(); }

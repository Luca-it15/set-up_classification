import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { blankSetup, newBuilderComponent, buildInstructions, validateBuilder, componentToBuilder } from '../src/utils/setupBuilder.js';
import { createSetupExport, exportSetupPng } from '../src/utils/setupExport.js';
import { PALETTES } from '../src/data.js';
import { DEFAULT_SETTINGS } from '../src/defaultSettings.js';
import { setLanguage, LANGUAGES } from '../src/i18n/index.js';
import { featureMessages } from '../src/i18n/featureMessages.js';
const report = JSON.parse(fs.readFileSync('examples/codex-workspace.ai-setup.json', 'utf8'));
const draft = { ...blankSetup(), name: 'Team setup', components: [{ ...newBuilderComponent(), type: 'knowledge_base', name: 'Manuale', path: 'handbook/' }] };
assert.equal(componentToBuilder({kind:'mcp_server',subtype:'configured_mcp_server',name:'github',path:'.codex/config.toml'}).path, 'github');
assert.equal(componentToBuilder({kind:'integration',subtype:'installed_plugin',name:'review-plugin',path:'.claude/settings.json'}).path, 'review-plugin');
assert.equal(componentToBuilder({kind:'document',name:'Guide'}).path, '');
assert.ok(validateBuilder(blankSetup()).name);
assert.throws(() => buildInstructions(blankSetup()));
assert.equal(buildInstructions(draft).filename, 'AGENTS.md');
assert.match(buildInstructions(draft).content, /Leggi `handbook\/`\./);
assert.equal(buildInstructions({ ...draft, tool: 'claude_code' }).filename, 'CLAUDE.md');
const conditional = { ...draft, components: [{ ...draft.components[0], when: 'modifichi il codice' }] };
assert.match(buildInstructions(conditional).content, /Quando modifichi il codice: Leggi/);
assert.doesNotMatch(buildInstructions(conditional).content, /^Leggi/m);
assert.ok(Object.keys(validateBuilder({ ...draft, components: [{ ...draft.components[0], path: 'bad`\npath' }] })).length);
for (const language of LANGUAGES) { setLanguage(language.code); assert.ok(buildInstructions(draft).content.includes('handbook/')); }
setLanguage('it');
assert.ok(Object.values(featureMessages).every(row => row.length === 5 && row.every(Boolean)));
const malicious = structuredClone(report);
malicious.workspace.name = '<script>alert(1)</script>';
malicious.components[0].name = '<img src=x onerror=alert(1)>';
malicious.components[0].path = 'PRIVATE_PATH_EXAMPLE';
malicious.extensions ||= {}; malicious.extensions.private_test = { secret: 'HIDDEN_SNAPSHOT_VALUE' };
const exported = createSetupExport(malicious, PALETTES.dark);
assert.doesNotMatch(exported.html, /<script|<img|PRIVATE_PATH_EXAMPLE|HIDDEN_SNAPSHOT_VALUE/);
assert.match(exported.html, /&lt;script&gt;/);
assert.match(createSetupExport(malicious, PALETTES.light, { includePaths: true }).html, /PRIVATE_PATH_EXAMPLE/);
assert.match(exported.svg, /<svg/);
assert.match(exported.svg, /class="node-plate"/);
assert.match(exported.mapSvg, /class="hotspot"/);
assert.match(exported.html, /class="map-frame"/);
assert.doesNotMatch(exported.html, /Inventario della mappa/);
assert.doesNotMatch(exported.html, /<script/i);
assert.ok(exported.height > 1000);
assert.ok(exported.html.includes('Content-Security-Policy'));
const empty = createSetupExport({ workspace: { name: 'Empty' }, components: [], relationships: [] }, PALETTES.light);
assert.match(empty.svg, /Nessuna componente/);
await assert.rejects(() => exportSetupPng({ width: 1400, height: 50000 }), /troppo grande/);
// Round trip generated instructions through the actual scanner for both hosts.
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'awdf-builder-test-'));
for (const tool of ['codex', 'claude_code']) {
  const root = path.join(tmp, tool); fs.mkdirSync(path.join(root, 'handbook'), { recursive: true });
  fs.writeFileSync(path.join(root, 'handbook', 'one.md'), '# First source');
  fs.writeFileSync(path.join(root, 'handbook', 'two.md'), '# Second source');
  const output = buildInstructions({ ...draft, tool }); fs.writeFileSync(path.join(root, output.filename), output.content);
  const settings = structuredClone(DEFAULT_SETTINGS); settings.initialized = true; settings.workspace.folders = [root]; settings.workspace.reference_tool = tool;
  const settingsFile = path.join(tmp, tool + '-settings.json'), outputFile = path.join(tmp, tool + '-report.json');
  fs.writeFileSync(settingsFile, JSON.stringify(settings));
  const result = spawnSync(process.execPath, ['scripts/describe-setup.mjs', root, outputFile, settingsFile], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
  const snapshot = JSON.parse(fs.readFileSync(outputFile)).extensions['org.awdf.description'];
  assert.ok(snapshot.snapshot.static_contracts.records.some(item => item.tool_id === tool && item.status === 'contract_present'));
}
console.log('Builder/export tests PASS: validation, conditional instructions, both host scanner round trips, locale coverage, HTML injection, path opt-in, empty and oversized export.');

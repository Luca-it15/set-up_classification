import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {spawnSync} from 'node:child_process';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.AWDF_NODE_MODULES ? path.join(process.env.AWDF_NODE_MODULES,'playwright') : 'playwright');
const scan=spawnSync(process.execPath,['scripts/test-configuration-links.mjs'],{encoding:'utf8'});
assert.equal(scan.status,0,scan.stderr);
const base=path.resolve('.tmp-evidence-checks/configuration');
const report=JSON.parse(fs.readFileSync(path.join(base,'report.json')));
const settings=JSON.parse(fs.readFileSync(path.join(base,'settings.json')));
let browser;
try {browser=await chromium.launch({headless:true});} catch {browser=await chromium.launch({headless:true,channel:'msedge'});}
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/api/report',r=>r.fulfill({json:report}));
 await page.route('**/api/settings',r=>r.fulfill({json:settings}));
 await page.goto('http://127.0.0.1:3000');
 const group=page.locator('.atlas-group-node').filter({has:page.locator('strong',{hasText:'Skills'})});
 await group.click();
 await page.getByRole('dialog').waitFor();
 assert.equal(await page.locator('.atlas-elements-list button').count(),4,'Support artifacts are not additional skill elements');
 const before=await page.locator('.atlas-stage .atlas-node strong').allTextContents();
 await page.locator('.atlas-elements-list button').filter({hasText:'Skill evaluator'}).click();
 assert.equal(await page.getByRole('dialog').count(),0);
 assert.equal(await page.locator('.atlas-detail h2').innerText(),'Skill evaluator');
 assert.deepEqual(await page.locator('.atlas-stage .atlas-node strong').allTextContents(),before,'Element selection preserves general map');
 await page.locator('.atlas-detail').getByText('Valuta una skill.',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Mostra tutta la rete',exact:true}).click();
 await page.getByRole('button',{name:'Configurazioni',exact:true}).click();
 assert.ok(await page.locator('.atlas-edges > path.configured').count()>=3);
 await page.getByLabel('Cerca elementi').fill('Registered');
 await page.locator('.atlas-inventory-list button').filter({hasText:'Registered'}).click();
 await page.locator('.atlas-detail').getByText('Collegato al setup',{exact:true}).waitFor();
 await page.locator('.atlas-detail .contract-panel summary').filter({hasText:'Configurata'}).click();
 await page.locator('.atlas-detail blockquote cite').filter({hasText:'config.toml'}).first().waitFor();
 await page.getByRole('button',{name:'Cancella ricerca'}).click();
 await page.getByLabel('Cerca elementi').fill('Disabled skill');
 await page.locator('.atlas-inventory-list button').filter({hasText:'Disabled skill'}).click();
 await page.locator('.atlas-detail').getByText('Disabilitato',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Cancella ricerca'}).click();
 await page.getByRole('button',{name:'Mostra tutta la rete',exact:true}).click();
 await page.getByRole('button',{name:'Tutti',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await group.click();
 await page.getByRole('dialog').waitFor();
 const bounds=await page.getByRole('dialog').boundingBox();
 assert.ok(bounds.x>=0 && bounds.x+bounds.width<=390 && bounds.height<=844);
 await page.keyboard.press('Escape');
 assert.equal(await page.getByRole('dialog').count(),0);
 assert.equal(await group.evaluate(el=>el===document.activeElement),true);
 await group.focus(); await page.keyboard.press('Enter');
 await page.getByRole('dialog').waitFor();
 await page.getByRole('button',{name:'Chiudi lista elementi'}).click();
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:path.join(base,'component-overview.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('Component UI PASS: grouped overview, named elements, stable map, configured source evidence and disabled skill state.');
} finally {await browser.close();}

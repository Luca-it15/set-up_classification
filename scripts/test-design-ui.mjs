import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.AWDF_NODE_MODULES ? path.join(process.env.AWDF_NODE_MODULES,'playwright') : 'playwright');
const base=path.resolve('.tmp-evidence-checks/design'), workspace=path.join(base,'workspace');
fs.mkdirSync(path.join(workspace,'llm-wiki'),{recursive:true});
fs.mkdirSync(path.join(workspace,'.codex'),{recursive:true});
fs.mkdirSync(path.join(workspace,'.claude'),{recursive:true});
fs.writeFileSync(path.join(workspace,'AGENTS.md'),'Before modifying code, consult `llm-wiki/index.md` and relevant pages.\n');
fs.writeFileSync(path.join(workspace,'CLAUDE.md'),'Before modifying code, consult `llm-wiki/index.md` and relevant pages.\n');
fs.writeFileSync(path.join(workspace,'.codex/config.toml'),'model = "fixture"\n');
fs.writeFileSync(path.join(workspace,'.claude/settings.json'),'{}');
fs.writeFileSync(path.join(workspace,'llm-wiki/index.md'),'# Shared project knowledge\n');
const settings={version:'1.0',initialized:true,workspace:{name:'Workspace condiviso',folders:[workspace],excluded:[],type:'project',purpose:'Verificare due tool con contratti distinti.',path_policy:'relative',analysis_level:'deep',tools:[{id:'codex',role:'primary',mode:'codex-cli',version:null},{id:'claude_code',role:'secondary',mode:'claude-code',version:null}],workflow_components:[{tool_id:'codex',path:'llm-wiki',required:true,scope:'.'},{tool_id:'claude_code',path:'llm-wiki',required:true,scope:'.'}]},viewer:{palette:'dark'}};
fs.writeFileSync(path.join(base,'settings.json'),JSON.stringify(settings));
const scan=spawnSync(process.execPath,['scripts/scan-setup.mjs',workspace,path.join(base,'report.json'),path.join(base,'settings.json')],{encoding:'utf8'});
assert.equal(scan.status,0,scan.stderr);
const report=JSON.parse(fs.readFileSync(path.join(base,'report.json')));
assert.deepEqual(new Set(report.extensions['org.awdf.contracts'].records.filter(r=>r.status==='contract_present').map(r=>r.tool_id)),new Set(['codex','claude_code']));
let browser;
try { browser=await chromium.launch({headless:true}); } catch { browser=await chromium.launch({headless:true,channel:'msedge'}); }
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.route('**/api/report',r=>r.fulfill({json:report}));
await page.route('**/api/settings',r=>r.request().method()==='PUT'?r.fulfill({status:500,json:{error:'Errore di test'}}):r.fulfill({json:settings}));
const noOverflow=async()=>assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
try {
 await page.goto('http://127.0.0.1:3000');
 await page.getByText('Workspace condiviso',{exact:true}).first().waitFor();
 assert.equal(await page.locator('.atlas-tool-node').count(),2);
 assert.equal(await page.locator('.atlas-primary-node').count(),1);
 assert.ok(await page.locator('.atlas-group-node').count()>0);
 await page.locator('.atlas-group-node').first().click();
 await page.getByRole('dialog').waitFor();
 await page.getByRole('button',{name:'Chiudi lista elementi'}).click();
 await page.locator('.atlas-contained[open]').waitFor();
 assert.ok(await page.locator('.atlas-contained button').count()>0);
 await page.getByRole('button',{name:'Mostra tutta la rete',exact:true}).click();
 assert.match(await page.locator('.atlas-primary-node').innerText(),/Codex/);
 const center=await page.locator('.atlas-primary-node').evaluate(el=>({x:el.offsetLeft+el.offsetWidth/2,y:el.offsetTop+el.offsetHeight/2}));
 assert.deepEqual(center,{x:610,y:465});
 await page.getByRole('button',{name:'Contratti',exact:true}).click();
 assert.equal(await page.locator('.atlas-edges > path.contractual').count(),4);
 assert.ok(await page.locator('.atlas-wikis').getByText('llm-wiki').count()>0);
 await page.screenshot({path:path.join(base,'two-tools.png'),fullPage:true});
 await page.getByRole('button',{name:'Codex Tool Collegato al setup',exact:true}).click();
 await page.locator('.atlas-detail .contract-panel .rule-card summary').filter({hasText:'codex'}).first().waitFor();
 await page.getByRole('button',{name:'Mostra tutta la rete',exact:true}).click();
 await page.getByLabel('Seleziona il tool AI da esplorare').selectOption({label:'Claude Code'});
 assert.equal(await page.locator('.atlas-tool-node').count(),1);
 assert.equal(await page.locator('.atlas-edges > path.contractual').count(),2);
 await page.locator('.atlas-connection-list > button').first().click();
 await page.locator('.atlas-detail blockquote cite').filter({hasText:'CLAUDE.md'}).first().waitFor();
 await page.getByRole('button',{name:'Mostra tutta la rete',exact:true}).click();
 await page.getByLabel('Seleziona il tool AI da esplorare').selectOption('all');
 await page.getByLabel('Cerca elementi').fill('no-such-resource');
 await page.getByText('Nessun elemento trovato',{exact:true}).waitFor();
 assert.equal(await page.locator('.atlas-node').count(),0);
 await page.getByRole('button',{name:'Cancella ricerca'}).click();
 assert.equal(await page.getByLabel('Cerca elementi').evaluate(el=>el===document.activeElement),true);
 await page.getByRole('button',{name:'Adatta',exact:true}).click();
 await page.getByRole('button',{name:'⚙ Impostazioni',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 await page.getByRole('button',{name:'Palette colori',exact:true}).click();
 await page.getByRole('button',{name:'Light Canvas chiaro',exact:true}).click();
 await page.getByRole('button',{name:'Chiudi settings',exact:true}).click();
 assert.equal(await page.locator('.app.light').count(),1);
 await page.screenshot({path:path.join(base,'light.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.emulateMedia({reducedMotion:'reduce'});
 await noOverflow();
 await page.screenshot({path:path.join(base,'mobile-map.png'),fullPage:true});
 await page.getByRole('button',{name:'⚙ Impostazioni',exact:true}).click();
 await page.getByLabel('Nome workspace',{exact:true}).fill('Bozza conservata');
 await page.getByRole('button',{name:'Salva',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Errore di test'}).waitFor();
 assert.equal(await page.getByLabel('Nome workspace',{exact:true}).inputValue(),'Bozza conservata');
 assert.equal(await page.getByRole('dialog').isVisible(),true);
 await page.keyboard.press('Escape');
 assert.equal(await page.getByRole('dialog').count(),0);
 assert.equal(await page.getByRole('button',{name:'⚙ Impostazioni',exact:true}).evaluate(el=>el===document.activeElement),true);
 await page.getByRole('button',{name:'Valutazione e roadmap',exact:true}).click();
 await noOverflow();
 await page.getByRole('button',{name:'▷ Prompt Lab',exact:true}).click();
 await noOverflow();
 await page.getByLabel('Prompt da simulare').fill('Consulta la wiki prima di modificare il codice.');
 await page.getByLabel('Tipo task',{exact:true}).selectOption('code_modification');
 await page.getByLabel('Percorso task',{exact:true}).fill('src/example.js');
 await page.getByRole('button',{name:'Simula routing',exact:true}).click();
 await noOverflow();
 await page.screenshot({path:path.join(base,'mobile-lab.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('Design UI PASS: two tools / AGENTS.md + CLAUDE.md, exact edges, source details, search/clear, light theme, mobile views, reduced motion, modal focus and failed-save recovery.');
} finally {await browser.close();}

import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.AWDF_NODE_MODULES ? path.join(process.env.AWDF_NODE_MODULES,'playwright') : 'playwright');
let browser;
try {browser=await chromium.launch({headless:true});} catch {browser=await chromium.launch({headless:true,channel:'msedge'});}
const base=path.resolve('.tmp-evidence-checks/configuration');
try {
 const page=await browser.newPage({viewport:{width:1440,height:1100},hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/api/report',r=>r.fulfill({json:JSON.parse(fs.readFileSync(path.join(base,'report.json')))}));
 await page.route('**/api/settings',r=>r.fulfill({json:JSON.parse(fs.readFileSync(path.join(base,'settings.json')))}));
 await page.goto('http://127.0.0.1:3000');
 const canvas=page.locator('.atlas-canvas'),stage=page.locator('.atlas-stage');
 await stage.waitFor();
 const camera=()=>stage.evaluate(el=>{const m=new DOMMatrix(getComputedStyle(el).transform);return {scale:m.a,x:m.e,y:m.f};});
 const changed=previous=>page.waitForFunction(previous=>document.querySelector('.atlas-stage').style.transform!==previous,previous);
 const beforeStyle=()=>stage.evaluate(el=>el.style.transform);
 await canvas.scrollIntoViewIfNeeded();
 const initial=await camera();
 const area=await canvas.boundingBox();
 const px=area.width*.4,py=area.height*.4;
 await page.mouse.move(area.x+px,area.y+py);
 let style=await beforeStyle();await page.mouse.wheel(0,-200);await changed(style);
 const wheel=await camera();assert.ok(wheel.scale>initial.scale);
 assert.ok(Math.abs((px-initial.x)/initial.scale-(px-wheel.x)/wheel.scale)<1,'Zoom keeps world point under cursor');
 const beforeResize=wheel.scale;
 await page.setViewportSize({width:1300,height:1000});
 await page.waitForFunction(scale=>Math.abs(new DOMMatrix(getComputedStyle(document.querySelector('.atlas-stage')).transform).a-scale)<.001,beforeResize);
 assert.ok(Math.abs((await camera()).scale-beforeResize)<.001,'Resize preserves manual zoom');
 await page.getByRole('button',{name:'Adatta',exact:true}).click();
 await canvas.scrollIntoViewIfNeeded();
 const fitted=await camera(), bounds=await canvas.boundingBox();
 await page.mouse.move(bounds.x+35,bounds.y+35);await page.mouse.down();
 await page.mouse.move(bounds.x+155,bounds.y+115,{steps:8});await page.mouse.up();
 const panned=await camera();assert.ok(panned.x-fitted.x>100 && panned.y-fitted.y>60,'Pan works even when the whole graph fits');
 await canvas.focus();style=await beforeStyle();await page.keyboard.press('+');await changed(style);
 assert.ok((await camera()).scale>panned.scale);
 const keyboardZoom=await camera();style=await beforeStyle();await page.keyboard.press('ArrowRight');await changed(style);
 assert.equal(Math.round((await camera()).x-keyboardZoom.x),-70);
 await page.keyboard.press('0');
 await page.getByRole('button',{name:'Aumenta zoom'}).click();
 const manual=await camera();
 await page.getByRole('button',{name:'Sposta vista a destra'}).click();
 assert.equal(Math.round((await camera()).x-manual.x),-100);
 await page.getByRole('button',{name:'Adatta',exact:true}).click();
 await canvas.scrollIntoViewIfNeeded();
 // A drag starting on a node must pan instead of opening its element dialog.
 const node=page.locator('.atlas-group-node').first();const nodeBounds=await node.boundingBox();
 await page.mouse.move(nodeBounds.x+nodeBounds.width/2,nodeBounds.y+nodeBounds.height/2);await page.mouse.down();
 await page.mouse.move(nodeBounds.x+nodeBounds.width/2+75,nodeBounds.y+nodeBounds.height/2+25,{steps:6});await page.mouse.up();
 assert.equal(await page.getByRole('dialog').count(),0);
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Adatta',exact:true}).click();await canvas.scrollIntoViewIfNeeded();
 const mobile=await canvas.boundingBox(),mid={x:mobile.x+mobile.width/2,y:Math.max(50,mobile.y+mobile.height/2)};
 const cdp=await page.context().newCDPSession(page);
 const touch=(id,x,y)=>({id,x,y,radiusX:2,radiusY:2});
 const pinchBefore=await camera();
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[touch(1,mid.x-30,mid.y),touch(2,mid.x+30,mid.y)]});
 style=await beforeStyle();
 await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[touch(1,mid.x-65,mid.y),touch(2,mid.x+65,mid.y)]});
 await changed(style);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 assert.ok((await camera()).scale>pinchBefore.scale*1.5,'Two-finger pinch zooms');
 const touchBefore=await camera();
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[touch(1,mid.x,mid.y)]});
 style=await beforeStyle();await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[touch(1,mid.x+50,mid.y+30)]});await changed(style);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 assert.ok((await camera()).x>touchBefore.x+30,'One-finger pan works');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
 await page.screenshot({path:path.join(base,'viewport-mobile.png')});
 assert.deepEqual(errors,[]);
 console.log('Viewport UI PASS: cursor-anchored wheel zoom, free pan, node drag, manual zoom persistence, buttons, keyboard, touch pinch/pan, mobile layout.');
} finally {await browser.close();}

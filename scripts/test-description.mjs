import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { providerEntries } from './lib/provider-links.mjs';
import { DESCRIPTION_KEY, describeInstructions } from '../src/evaluator/description.js';
import { classifyDescription } from '../src/evaluator/static-classifier.js';
import { validateAwdfAsync } from '../src/utils/appUtils.js';
import { validateAwdfDocument } from './validate-awdf.mjs';
import { DEFAULT_SETTINGS } from '../src/defaultSettings.js';
import { buildGraphModel } from '../src/utils/graphModel.js';
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'awdf-description-'));
const workspace = path.join(temp, 'workspace');
fs.mkdirSync(path.join(workspace, '.codex'), { recursive: true });
fs.mkdirSync(path.join(workspace, 'manuali'));
const config = 'model_provider = "proxy"\n[model_providers.proxy]\nbase_url = "http://127.0.0.1:8787/v1"\n';
fs.writeFileSync(path.join(workspace, '.codex/config.toml'), config);
fs.writeFileSync(path.join(workspace, 'proxy.toml'), '[proxy]\nmodule = "headroom.proxy"\nendpoint = "http://127.0.0.1:8787/v1"\n');
fs.writeFileSync(path.join(workspace, 'AGENTS.md'), '# Regole\n\n- Run `npm test` before committing.\n\n- Read `manuali/`.\n\nNon eseguire deploy senza richiesta.\n');
fs.writeFileSync(path.join(workspace, 'manuali/architettura.md'), '# Architettura\nArchitettura del progetto.');
fs.writeFileSync(path.join(workspace, 'manuali/procedure.md'), '# Procedure\nProcedure operative.');
const output = path.join(temp, 'description.json');
const settings = structuredClone(DEFAULT_SETTINGS); settings.initialized = true; settings.workspace.folders = [workspace];
fs.writeFileSync(path.join(temp, 'missing-settings.json'), JSON.stringify(settings));
const result = spawnSync(process.execPath, ['scripts/describe-setup.mjs', workspace, output, path.join(temp, 'missing-settings.json')], { encoding: 'utf8' });
assert.equal(result.status, 0, result.stderr || result.stdout);
const report = JSON.parse(fs.readFileSync(output, 'utf8'));
assert.deepEqual(validateAwdfDocument(report), []);
assert.equal(report.extensions['org.awdf.evaluation'], undefined);
assert.deepEqual(report.assessments, []);
assert.deepEqual(report.findings, []);
const description = report.extensions[DESCRIPTION_KEY];
assert.ok(description.instruction_sources.some(item => item.blocks.some(block => block.description.includes('Non eseguire deploy'))));
const provider = report.components.find(item => item.subtype === 'configured_model_provider');
assert.equal(provider.name, 'Headroom');
const configNode = report.components.find(item => item.properties?.format === 'codex_project_config');
assert.ok(report.relationships.some(item => item.source_id === configNode.id && item.target_id === provider.id));
assert.ok(report.relationships.some(item => item.target_id === configNode.id && report.components.some(component => component.id === item.source_id && component.properties?.tool_id === 'codex')));
const corpus = description.knowledge_bases.find(item => item.path === 'manuali');
assert.equal(corpus.source_paths.length, 2);
assert.equal(corpus.status, 'consultation_prescribed');
const evaluation = classifyDescription(report);
assert.equal(evaluation.outcomes.find(item => item.rule_id === 'instructions.validation-command').outcome, 'pass');
assert.equal(evaluation.summary.overall_score, null);
assert.ok(evaluation.rules.every(item => item.sources.length));
const loaded = await validateAwdfAsync(report);
assert.deepEqual(await validateAwdfAsync(loaded), loaded);
buildGraphModel(loaded);
// An unrecognized/negative instruction cannot earn the positive command check.
const changed = structuredClone(report);
const source = changed.extensions[DESCRIPTION_KEY];
source.snapshot.static_contracts.records = [];
source.snapshot.files.find(item => item.path === 'AGENTS.md').content = 'Do not run `npm test`.\n';
source.instruction_sources = describeInstructions(source.snapshot, source.instruction_sources.map(({ blocks, content_status, ...item }) => item));
assert.equal(classifyDescription(changed).outcomes.find(item => item.rule_id === 'instructions.validation-command').outcome, 'insufficient_evidence');
await assert.rejects(() => validateAwdfAsync(changed), /integrity|Snapshot/);
assert.equal(providerEntries(config)[0].name, 'proxy');
assert.equal(providerEntries(config, [{ path: 'wrong.toml', content: 'module="headroom.proxy"\nendpoint="http://127.0.0.1:9999/v1"' }])[0].name, 'proxy');
assert.equal(providerEntries('openai_provider="http://127.0.0.1:8787/v1"')[0].selection_key, 'openai_provider');
assert.equal(providerEntries('model_provider="http://user:password@127.0.0.1:8787/v1?token=secret"')[0].endpoint, 'http://127.0.0.1:8787/v1');
for (const content of ['# Examples\nRun `npm test` before committing.', '```\nRun `npm test` before committing.\n```', '<!--\nRun `npm test` before committing.\n-->', '> Run `npm test` before committing.']) {
  const candidate = structuredClone(report);
  const d = candidate.extensions[DESCRIPTION_KEY];
  d.snapshot.static_contracts.records = [];
  d.snapshot.files.find(file => file.path === 'AGENTS.md').content = content;
  d.instruction_sources = describeInstructions(d.snapshot, d.instruction_sources.map(({blocks,content_status,...item}) => item));
  assert.equal(classifyDescription(candidate).outcomes.find(item => item.rule_id === 'instructions.validation-command').outcome, 'insufficient_evidence');
}
const artifacts = path.resolve('.tmp-evidence-checks/description');
fs.mkdirSync(artifacts, {recursive:true});
fs.writeFileSync(path.join(artifacts,'report.json'), JSON.stringify(report));
fs.writeFileSync(path.join(artifacts,'settings.json'), JSON.stringify(settings));
console.log('Description integration tests passed: provider chain, Markdown binding, source instructions, static rules, integrity and import replay.');

